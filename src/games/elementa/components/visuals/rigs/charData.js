for (const [id, def] of Object.entries(CHAR_SPRITES)) {
  def.id = id
  def.grid = def.rows.length
  def.palette = def.palette ?? tone(def.color)
}

/** Every row the same length (a quick check for a new sprite). */
export function spriteProblems() {
  return Object.values(CHAR_SPRITES).flatMap((d) => d.rows.filter((r) => r.length !== d.grid).map((r, i) => `${d.id}: row ${i} has ${r.length}, expected ${d.grid}`))
}
